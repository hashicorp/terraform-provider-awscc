package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
)

// modulePath is the Go module path; generated import paths are built from it.
const modulePath = "github.com/hashicorp/terraform-provider-awscc"

// writeCorpus writes each generated artifact's code and test file to
// cfg.outputRoot/<pathSuffix>/<file>, creating directories as needed. Returns the
// number of files written. A generate error in any result aborts before writing
// it (never write partial/failed output over good files).
func writeCorpus(cfg config, results []genResult) (int, error) {
	written := 0
	for _, r := range results {
		if r.err != nil {
			return written, fmt.Errorf("%s %s: %w", r.p.cfType, r.a.kind, r.err)
		}
		dir := filepath.Join(cfg.outputRoot, r.a.pathSuffix)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return written, fmt.Errorf("creating %s: %w", dir, err)
		}
		for _, fw := range []struct {
			name string
			data []byte
		}{
			{r.a.codeFile, r.code},
			{r.a.testFile, r.test},
		} {
			path := filepath.Join(dir, fw.name)
			if err := os.WriteFile(path, fw.data, 0o644); err != nil {
				return written, fmt.Errorf("writing %s: %w", path, err)
			}
			written++
		}
	}
	return written, nil
}

const registrationHeader = `// Copyright IBM Corp. 2021, 2026
// SPDX-License-Identifier: MPL-2.0

// Code generated by bigdiffer; DO NOT EDIT.

package provider
`

// registrationPackages returns the sorted set of service-package path suffixes
// (e.g. "aws/logs") that have at least one generated artifact. One blank import
// per such package is what makes its generated init() — and therefore every
// factory it registers — run in the built provider.
func registrationPackages(cfg config, rows []resourceRow) ([]string, error) {
	seen := make(map[string]struct{})
	for _, row := range rows {
		p, err := generationPlan(row, cfg.prefix, cfg.cacheDir)
		if err != nil {
			return nil, fmt.Errorf("plan %s: %w", row.CloudFormationTypeName, err)
		}
		for _, a := range p.artifacts {
			seen[a.pathSuffix] = struct{}{}
		}
	}
	suffixes := make([]string, 0, len(seen))
	for s := range seen {
		suffixes = append(suffixes, s)
	}
	sort.Strings(suffixes)
	return suffixes, nil
}

// emitRegistration renders the single blank-import registration file that
// replaces the legacy resources.go/*_data_sources.go directive files: one import
// per service package with a generated artifact, so every generated init() runs.
func emitRegistration(cfg config, rows []resourceRow) ([]byte, error) {
	suffixes, err := registrationPackages(cfg, rows)
	if err != nil {
		return nil, err
	}

	var b bytes.Buffer
	b.WriteString(registrationHeader)
	b.WriteString("\nimport (\n")
	for _, s := range suffixes {
		fmt.Fprintf(&b, "\t_ %q\n", modulePath+"/internal/"+s)
	}
	b.WriteString(")\n")

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting registration file:\n%s\n%w", b.Bytes(), err)
	}
	return formatted, nil
}
