// modulePath is the Go module path; generated import paths are built from it.
const modulePath = "github.com/hashicorp/terraform-provider-awscc"

// File-mode permissions for generated output.
const (
	dirPerm  os.FileMode = 0o755
	filePerm os.FileMode = 0o644
)

// writeArtifact writes one generated artifact's code and test file to
// cfg.outputRoot/r.a.pathSuffix/, creating directories as needed. It does not
// check r.err — callers decide what to do with a failed result.
func writeArtifact(cfg config, r genResult) error {
	dir := filepath.Join(cfg.outputRoot, r.a.pathSuffix)
	if err := os.MkdirAll(dir, dirPerm); err != nil {
		return fmt.Errorf("creating %s: %w", dir, err)
	}
	for _, fw := range []struct {
		name string
		data []byte
	}{
		{r.a.codeFile, r.code},
		{r.a.testFile, r.test},
	} {
		path := filepath.Join(dir, fw.name)
		if err := os.WriteFile(path, fw.data, filePerm); err != nil {
			return fmt.Errorf("writing %s: %w", path, err)
		}
	}
	return nil
}

// writeCorpus writes each generated artifact's code and test file to
// cfg.outputRoot/<pathSuffix>/<file>, creating directories as needed. Returns the
// number of files written. A generate error in any result aborts before writing
// it (never write partial/failed output over good files). Used by the offline
// full-corpus path (-generate), where every type in the committed overlay is
// expected to generate cleanly and a failure is exceptional; the live
// incremental path (-update) promotes per-artifact instead (refreshCandidate).
func writeCorpus(cfg config, results []genResult) (int, error) {
	written := 0
	for _, r := range results {
		if r.err != nil {
			return written, fmt.Errorf("%s %s: %w", r.p.cfType, r.a.kind, r.err)
		}
		if err := writeArtifact(cfg, r); err != nil {
			return written, err
		}
		written += 2
	}
	return written, nil
}

const registrationHeader = `// Copyright IBM Corp. 2021, 2026
// SPDX-License-Identifier: MPL-2.0

// Code generated by bigdiffer; DO NOT EDIT.

package provider
`

// registrationPackages returns the sorted set of service-package path suffixes
// (e.g. "aws/logs") that have at least one generated artifact. One blank import
// per such package is what makes its generated init() — and therefore every
// factory it registers — run in the built provider.
func registrationPackages(cfg config, rows []resourceRow) ([]string, error) {
	seen := make(map[string]struct{})
	for _, row := range rows {
		p, err := generationPlan(row, cfg.prefix, cfg.cacheDir)
		if err != nil {
			return nil, fmt.Errorf("plan %s: %w", row.CloudFormationTypeName, err)
		}
		for _, a := range p.artifacts {
			seen[a.pathSuffix] = struct{}{}
		}
	}
	suffixes := make([]string, 0, len(seen))
	for s := range seen {
		suffixes = append(suffixes, s)
	}
	sort.Strings(suffixes)
	return suffixes, nil
}

// emitRegistration renders the single blank-import registration file that
// replaces the legacy resources.go/*_data_sources.go directive files: one import
// per service package with a generated artifact, so every generated init() runs.
func emitRegistration(cfg config, rows []resourceRow) ([]byte, error) {
	suffixes, err := registrationPackages(cfg, rows)
	if err != nil {
		return nil, err
	}

	var b bytes.Buffer
	b.WriteString(registrationHeader)
	b.WriteString("\nimport (\n")
	for _, s := range suffixes {
		fmt.Fprintf(&b, "\t_ %q\n", modulePath+"/internal/"+s)
	}
	b.WriteString(")\n")

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting registration file:\n%s\n%w", b.Bytes(), err)
	}
	return formatted, nil
}

// emitImportExamples renders import_examples_gen.json: one entry per resource
// that generates a resource artifact, carrying its primary-identifier names (the
// raw, non-snake-cased names, as the legacy aggregate uses) and its
// list-resource flag. Mirrors schema/main.go's GenerateResourceImportExamples,
// which likewise re-derives the identifiers via the template data.
func emitImportExamples(cfg config, rows []resourceRow) ([]byte, error) {
	ui := &cli.BasicUi{Writer: io.Discard, ErrorWriter: io.Discard}

	var examples []codegen.ImportExample
	for _, row := range rows {
		p, err := generationPlan(row, cfg.prefix, cfg.cacheDir)
		if err != nil {
			return nil, fmt.Errorf("plan %s: %w", row.CloudFormationTypeName, err)
		}

		var res *genArtifact
		for i := range p.artifacts {
			if p.artifacts[i].kind == artifactResource {
				res = &p.artifacts[i]
				break
			}
		}
		if res == nil {
			continue // resource generation suppressed; no import example
		}

		td, err := codegen.GenerateTemplateData(ui, p.schemaFile, codegen.ResourceType, res.tfType, res.packageName, cfg.servicesPath, p.pathAwareNames)
		if err != nil {
			return nil, fmt.Errorf("template data %s: %w", p.cfType, err)
		}

		identifier := make([]string, 0, len(td.PrimaryIdentifier))
		for _, v := range td.PrimaryIdentifier {
			identifier = append(identifier, v.Name)
		}

		examples = append(examples, codegen.ImportExample{
			ResourceName:         res.tfType,
			GenerateListResource: res.listResource,
			Identifier:           identifier,
		})
	}

	return codegen.GenerateImportExamples(examples)
}
