// runCheck is reconcile's pipeline with promotion switched off
// (bigdiffer-design.md §0, story 3; §6): the same generate -> compile ->
// decide gate as -reconcile,
// against the same offline row source (reconcileCandidates), but nothing is
// ever written to internal/, the schema cache, all_schemas.hcl, or the
// CHANGELOG — check is read-only end to end. It reports every failure and
// exits non-zero on either a failure or any output-diff (regenerated bytes
// != committed bytes, even though they compile) — the "you changed the
// engine but didn't -reconcile and commit" gap TestFullCorpusParity used to
// guard and the legacy engine retires (bigdiffer-design.md §10). A
// non-engine PR touches no template/codegen/naming path, so regeneration is
// a no-op and check passes with zero diff; an engine PR must run -reconcile
// and commit the result until check is clean.
//
// fullDocs (the -check-docs-full flag) additionally renders the registry
// docs themselves (tfplugindocs, via a real built binary extracted from the
// staged tree) and diffs them against committed docs/
// (bigdiffer-design.md §6, "Documentation is part of the same gated
// pipeline").
// Off by default: it is markedly heavier than everything else -check does
// (a real `go build` of the whole provider plus a `terraform providers
// schema -json` call, vs. -check's otherwise offline, no-extra-build
// diffing), so it stays opt-in until proven fast/stable enough to run on
// every PR — the cheap tier (import_examples_gen.json freshness) already
// runs unconditionally and is what -check's CI wiring (item 5) uses today.
func runCheck(ctx context.Context, allSchemasPath, checkoutPath string, fullDocs bool) error {
	cfg, overlayRows, err := loadOverlay(allSchemasPath)
	if err != nil {
		return err
	}
	checkout, err := parseCheckout(checkoutPath)
	if err != nil {
		return fmt.Errorf("reading checkout %s: %w", checkoutPath, err)
	}

	cands, frozenSkipped, cacheMissSkipped := reconcileCandidates(overlayRows, cfg.cacheDir)
	stepf("Checking %d type(s) offline against the committed overlay + cache (%d frozen, %d cache-miss, skipped)…", len(cands), frozenSkipped, cacheMissSkipped)
	today := todayString()

	overlayContent, err := os.ReadFile(allSchemasPath)
	if err != nil {
		return fmt.Errorf("reading overlay %s: %w", allSchemasPath, err)
	}

	// Identical to runReconcile: overlayRows doubles as the offline row
	// source's own "base" for projectRows (compile.go) — offline, there is
	// nothing fresher than what is already committed.
	settled, err := settleBatch(ctx, cfg, cands, nil, string(overlayContent), overlayRows, checkout, today)
	if err != nil {
		return err
	}
	// check never promotes, so unlike runReconcile there is no promoteStaged
	// call to make this directory's contents durable — it exists only long
	// enough for the diff scan below to compare against it, then it is
	// discarded either way.
	defer func() { _ = os.RemoveAll(settled.stagingDir) }()

	var problems []string

	// Identical rationale to runReconcile/runSync: every candidate here is
	// classPresentUnchanged, so every failure is, by construction, a
	// machinery failure. check cannot promote anything regardless, but it
	// still must not report a plain output-diff for a type that actually
	// failed to regenerate at all -- that is a failure, a stronger and more
	// specific finding than "differs from committed," and is reported as
	// such, first.
	if failures := machineryFailures(settled); len(failures) > 0 {
		var b strings.Builder
		fmt.Fprintf(&b, "%d type(s) failed to regenerate or compile:", len(failures))
		for _, f := range failures {
			fmt.Fprintf(&b, "\n  %s", f.cfType)
			for _, a := range f.artifacts {
				fmt.Fprintf(&b, "\n    %s", a)
			}
		}
		problems = append(problems, b.String())
	}

	// Output-diff scan: everything settleBatch staged under stagingDir/out
	// and stagingDir/cache mirrors what promoteStaged (sync.go) would copy
	// onto cfg.outputRoot/cfg.cacheDir if this were a -reconcile run instead
	// -- compare bytes directly against the real, committed trees rather
	// than actually promoting, so check stays read-only. Only staged files
	// are compared: an artifact the gate dropped or that failed to generate
	// leaves its committed file untouched (kept as last-good), which cannot
	// differ from itself.
	diffs, err := diffStagedTrees(cfg, settled.stagingDir)
	if err != nil {
		return fmt.Errorf("comparing staged output to committed: %w", err)
	}
	if len(diffs) > 0 {
		problems = append(problems, fmt.Sprintf("%d file(s) differ from committed output (engine change not yet -reconcile'd and committed):\n  %s", len(diffs), strings.Join(diffs, "\n  ")))
	}

	// Docs freshness, cheap tier (bigdiffer-design.md §6, "Documentation is
	// part of the same gated pipeline"): import_examples_gen.json is a pure
	// function of the row set a -reconcile would promote (projectRows, the
	// same in-memory projection the compile gate's own fixpoint uses — never
	// a hand-rolled parallel reimplementation) plus the cached schema bytes
	// each row's plan reads, so it can be recomputed and diffed here with no
	// external tools and no disk writes at all — catching "code changed (or
	// the engine that reads schemas to build it did), the aggregate was not
	// regenerated" without needing tfplugindocs or a built provider binary
	// (that is the full tier's job, below). Deliberately checked even when
	// cands and diffs above are both clean: the aggregate is a function of
	// the *whole* row set, not just this run's candidates, so a stale copy
	// can exist even when every candidate this run regenerates
	// byte-identical.
	//
	// Must run after diffStagedTrees, not before: diffImportExamples reads
	// the committed schema cache (cfg.cacheDir), not settleBatch's staged
	// one, which is only a safe substitute because diffStagedTrees above has
	// already gated on committed-vs-staged cache drift — see
	// diffImportExamples' own doc comment for why that makes the two
	// equivalent whenever this line is even reached.
	if diff, err := diffImportExamples(cfg, string(overlayContent), overlayRows, checkout, settled.decisions); err != nil {
		return fmt.Errorf("checking import examples freshness: %w", err)
	} else if diff != "" {
		problems = append(problems, diff)
	}

	// Docs freshness, full tier (bigdiffer-design.md §6, "Documentation is
	// part of the same gated pipeline"), opt-in via -check-docs-full:
	// renders the registry docs themselves (tfplugindocs, via a real built
	// binary extracted from the staged tree — docs_full_check.go) and diffs
	// against committed docs/. Deliberately last: it is the heaviest of
	// every check -check runs (a real go build of the whole provider plus a
	// terraform providers schema -json call), so every cheaper, offline
	// check above gets a chance to fail first and skip paying for it.
	if fullDocs {
		rows, err := projectRows(string(overlayContent), overlayRows, checkout, settled.decisions)
		if err != nil {
			return fmt.Errorf("projecting rows for the full-tier docs check: %w", err)
		}
		diffs, err := diffRenderedDocs(ctx, cfg, settled.stagingDir, rows)
		if err != nil {
			return fmt.Errorf("checking rendered docs freshness: %w", err)
		}
		if len(diffs) > 0 {
			problems = append(problems, fmt.Sprintf("%d rendered doc file(s) differ from committed output (engine or docs-template change not yet -reconcile'd/-docs'd and committed):\n  %s", len(diffs), strings.Join(diffs, "\n  ")))
		}
	}

	if len(problems) > 0 {
		return errors.New(strings.Join(problems, "\n"))
	}

	infof("bigdiffer: -check passed; %d type(s) regenerate byte-identical to committed output.", len(cands))
	return nil
}

// diffImportExamples recomputes import_examples_gen.json from the row set a
// -reconcile would promote right now (projectRows, the identical projection
// the compile gate's fixpoint already uses) and compares it byte-for-byte
// against the committed file. Returns a non-empty problem description on any
// difference (including a missing committed file, which counts as a diff —
// there is a genuine aggregate to -reconcile and commit), or "" when the
// committed copy is already current. Never writes anything; cfg is only used
// to resolve cfg.importExamplesPath and each row's cached schema bytes.
//
// Reads cfg.cacheDir — the committed cache, not settleBatch's staged cache —
// via emitImportExamples's own generationPlan calls. That is deliberately
// safe rather than an oversight: diffStagedTrees (the caller, run first)
// already fails the check on any committed-vs-staged cache drift, so by the
// time this runs, either the check has already failed for that reason, or
// committed cache == staged cache == what -reconcile would promote, and
// recomputing from either is equivalent. The only visible effect of reading
// committed instead of staged is cosmetic: in a run where the cache itself
// also drifted, this diff will not additionally enumerate the import-examples
// mismatch that round (diffStagedTrees' cache diff already reported it) —
// both converge to clean after one real -reconcile + commit either way.
func diffImportExamples(cfg config, overlayContent string, base []resourceRow, checkout map[string]bool, decisions map[string]policyDecision) (string, error) {
	rows, err := projectRows(overlayContent, base, checkout, decisions)
	if err != nil {
		return "", fmt.Errorf("projecting rows: %w", err)
	}
	want, err := emitImportExamples(cfg, rows)
	if err != nil {
		return "", fmt.Errorf("recomputing import examples: %w", err)
	}
	got, err := os.ReadFile(cfg.importExamplesPath)
	if err != nil {
		if os.IsNotExist(err) {
			return fmt.Sprintf("%s does not exist (engine change not yet -reconcile'd and committed)", relToRepoRoot(cfg, cfg.importExamplesPath)), nil
		}
		return "", fmt.Errorf("reading committed %s: %w", cfg.importExamplesPath, err)
	}
	if !bytes.Equal(want, got) {
		return fmt.Sprintf("%s differs from committed output (engine change not yet -reconcile'd and committed)", relToRepoRoot(cfg, cfg.importExamplesPath)), nil
	}
	return "", nil
}

// diffStagedTrees compares every file staged under stagingDir/out and
// stagingDir/cache against its real, committed counterpart
// (cfg.outputRoot/cfg.cacheDir respectively), returning the destination
// paths (relative to the repo root, for a stable and readable report) of
// every file whose bytes differ or that does not yet exist committed at
// all (a type recovering from suppression via a machinery fix, with no
// prior committed artifact to compare against, still counts as a diff --
// there is genuinely new output to -reconcile and commit). Paths are
// sorted for a deterministic report.
//
// Deliberately one-directional (staged -> committed, never the reverse):
// this mirrors promoteStaged's own copyTree (sync.go), which overwrites
// files present in the staged tree but never deletes a committed file the
// current templates/codegen no longer emit at all. check's contract is
// "passes iff running -reconcile and committing the result would be a
// no-op" -- scanning the other direction too would make check fail on a
// state -reconcile itself cannot fix (an orphaned file neither command
// removes), which is a corpus-wide property of both commands, not a gap
// specific to this scan (bigdiffer-design.md §6, "Neither -reconcile nor
// -check removes orphaned output"). If orphan cleanup is ever added to
// -reconcile, this scan needs the reverse walk added at the same time.
func diffStagedTrees(cfg config, stagingDir string) ([]string, error) {
	var diffs []string
	for _, pair := range []struct{ staged, committed string }{
		{filepath.Join(stagingDir, "out"), cfg.outputRoot},
		{filepath.Join(stagingDir, "cache"), cfg.cacheDir},
	} {
		if _, err := os.Stat(pair.staged); os.IsNotExist(err) {
			continue // nothing staged under this root at all
		}
		err := filepath.Walk(pair.staged, func(path string, info os.FileInfo, err error) error {
			if err != nil {
				return err
			}
			if info.IsDir() {
				return nil
			}
			rel, err := filepath.Rel(pair.staged, path)
			if err != nil {
				return err
			}
			stagedBytes, err := os.ReadFile(path)
			if err != nil {
				return fmt.Errorf("reading staged %s: %w", path, err)
			}
			committedPath := filepath.Join(pair.committed, rel)
			committedBytes, err := os.ReadFile(committedPath)
			if err != nil {
				if os.IsNotExist(err) {
					diffs = append(diffs, relToRepoRoot(cfg, committedPath))
					return nil
				}
				return fmt.Errorf("reading committed %s: %w", committedPath, err)
			}
			if !bytes.Equal(stagedBytes, committedBytes) {
				diffs = append(diffs, relToRepoRoot(cfg, committedPath))
			}
			return nil
		})
		if err != nil {
			return nil, err
		}
	}
	sort.Strings(diffs)
	return diffs, nil
}

// relToRepoRoot renders an absolute path relative to cfg.repoRoot for a
// readable report; falls back to the absolute path if it is somehow outside
// the repo root (should not happen for staged/committed output paths, but a
// readable absolute path is a safer failure mode than an error here).
func relToRepoRoot(cfg config, path string) string {
	rel, err := filepath.Rel(cfg.repoRoot, path)
	if err != nil {
		return path
	}
	return rel
}
